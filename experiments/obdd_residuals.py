"""Count residual truth tables; this is finite evidence, not an asymptotic proof."""

from __future__ import annotations

import argparse
import csv
import io
from itertools import product
from pathlib import Path
from typing import Callable

ROOT = Path(__file__).resolve().parents[1]


def disjointness(bits: tuple[int, ...]) -> int:
    """Interpret bits as a followed by b and test their disjointness."""
    if len(bits) % 2:
        raise ValueError("An even number of input bits is required.")
    m = len(bits) // 2
    return int(all(not (bits[i] and bits[m + i]) for i in range(m)))


def residual_widths(
    function: Callable[[tuple[int, ...]], int],
    order: tuple[int, ...],
) -> tuple[int, ...]:
    """Minimum layered widths, including the initial and terminal layers."""
    count = len(order)
    if sorted(order) != list(range(count)):
        raise ValueError("The order must be a permutation of the input positions.")
    truth = bytearray()
    for ordered_bits in product((0, 1), repeat=count):
        assignment = [0] * count
        for position, bit in zip(order, ordered_bits):
            assignment[position] = bit
        output = function(tuple(assignment))
        if output not in (0, 1):
            raise ValueError("The function must return a Boolean value.")
        truth.append(output)
    widths = []
    for cut in range(count + 1):
        suffix_count = 1 << (count - cut)
        residuals = {
            bytes(truth[start : start + suffix_count])
            for start in range(0, len(truth), suffix_count)
        }
        widths.append(len(residuals))
    return tuple(widths)


def rows(max_m: int) -> list[dict[str, int]]:
    result = []
    for m in range(1, max_m + 1):
        grouped = residual_widths(disjointness, tuple(range(2 * m)))
        order = tuple(position for i in range(m) for position in (i, m + i))
        interleaved = residual_widths(disjointness, order)
        result.append(
            {
                "m": m,
                "input_bits": 2 * m,
                "grouped_cut_width": grouped[m],
                "grouped_max_width": max(grouped),
                "interleaved_max_width": max(interleaved),
            }
        )
    return result


def artifact_contents(max_m: int) -> dict[Path, str]:
    observations = rows(max_m)
    stream = io.StringIO(newline="")
    writer = csv.DictWriter(
        stream, fieldnames=list(observations[0]), lineterminator="\n"
    )
    writer.writeheader()
    writer.writerows(observations)
    latex = [
        "% Generated by experiments/obdd_residuals.py; do not edit.",
        r"\begin{tabular}{rrrr}",
        r"\toprule",
        r"$m$ & Grouped cut & Grouped maximum & Interleaved maximum \\",
        r"\midrule",
    ]
    for row in observations:
        latex.append(
            f"{row['m']} & {row['grouped_cut_width']} & "
            f"{row['grouped_max_width']} & {row['interleaved_max_width']} "
            + r"\\"
        )
    latex.extend([r"\bottomrule", r"\end{tabular}", ""])
    return {
        ROOT / "data/obdd_widths.csv": stream.getvalue(),
        ROOT / "data/obdd_widths.tex": "\n".join(latex),
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--max-m", type=int, default=7)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if not 1 <= args.max_m <= 10:
        parser.error("--max-m must be between 1 and 10 for this exhaustive tool.")
    stale = []
    for path, content in artifact_contents(args.max_m).items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
    if stale:
        print("Generated data is stale: " + ", ".join(stale))
        print("Run make experiments.")
        return 1
    print(f"Finite data {'verified' if args.check else 'generated'}: 1 <= m <= {args.max_m}.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
