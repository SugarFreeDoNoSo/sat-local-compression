"""Check a source-pinned review request, not mathematical correctness or review."""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import re
import sys


ROOT = Path(__file__).resolve().parents[1]
MANIFEST = "research/review-packet.json"
DOCUMENT = "docs/independent-review-packet.md"
SOURCE_PATTERNS = (
    "paper/*.tex", "paper/sections/*.tex", "paper/*.bib",
    "formal/*.lean", "formal/ResidualWidths/*.lean", "formal/*.toml",
    "formal/*.json", "formal/lean-toolchain", "lean-toolchain",
    "formal/README.md", "experiments/*.py", "data/*.csv", "data/*.tex", "data/*.json",
    "tests/test_graph_orders.py", "tests/test_residuals.py",
    "tests/test_graph_signatures.py", "tests/test_matching_certificates.py",
    "tests/test_formal_audit.py",
    "research/claims.json", "scripts/check_formal.py", "scripts/setup_lean.py",
    "docs/w01-evaluator-audit.md", "docs/w02-kt-comparison.md",
    "docs/w03-restricted-model.md", "docs/literature.md",
    "docs/w04-transfer-audit.md", "docs/wave-07-graph-signatures.md",
    "docs/wave-08-matching-certificates.md",
)


def snapshot_paths(root: Path) -> set[str]:
    return {
        path.relative_to(root).as_posix()
        for pattern in SOURCE_PATTERNS for path in root.glob(pattern)
        if path.is_file()
    }


def require(condition: bool, message: str) -> None:
    if not condition:
        raise ValueError(message)


def validate(root: Path, packet: dict, register: dict) -> None:
    require(packet["schema_version"] == 1, "Unsupported review-packet schema")
    require(packet["kind"] == "review-request", "Packet must remain a review request")
    require(re.fullmatch(r"[0-9a-f]{40}", packet["source_revision"]) is not None,
            "Source revision must be a full commit SHA")
    hashes = packet["source_sha256"]
    require(set(hashes) == snapshot_paths(root),
            "Snapshot file set changed; reassess the review scope and repin it")
    for name, expected in hashes.items():
        path = root / name
        require(path.resolve().is_relative_to(root.resolve()),
                f"Snapshot path escapes the checkout: {name}")
        require(hashlib.sha256(path.read_bytes()).hexdigest() == expected,
                f"Source changed since the review snapshot: {name}")
    claims = register["claims"]
    ids = [claim["id"] for claim in claims]
    require(len(ids) == len(set(ids)), "Duplicate claim-register IDs")
    covered = []
    unit_ids = []
    for unit in packet["review_units"]:
        unit_ids.append(unit["id"])
        require(re.fullmatch(r"[a-z][a-z0-9-]*", unit["id"]) is not None,
                "Invalid review-unit ID")
        require(unit["title"].strip() and unit["claim_ids"]
                and unit["sources"] and unit["questions"],
                f"Incomplete review unit: {unit['id']}")
        require(all(question.strip() for question in unit["questions"]),
                f"Empty review question: {unit['id']}")
        require(all(name in hashes for name in unit["sources"]),
                f"Unpinned reading source: {unit['id']}")
        covered.extend(unit["claim_ids"])
    require(len(unit_ids) == len(set(unit_ids)), "Duplicate review-unit IDs")
    require(len(covered) == len(set(covered)), "Duplicate review claim coverage")
    require(set(covered) == set(ids), "Review packet must cover every claim exactly once")


def render(packet: dict, register: dict) -> str:
    claims = {claim["id"]: claim for claim in register["claims"]}
    sha = packet["source_revision"]
    repo = "https://github.com/SugarFreeDoNoSo/sat-local-compression"
    lines = [
        "<!-- Generated by scripts/check_review_packet.py --write; edit the manifest. -->",
        "# Independent mathematical review request", "",
        "**Preparation only; no independent human review or endorsement is recorded.**",
        "This packet does not close W01/#3 or the publication gates in W06/#8.",
        "No reviewer has been selected or contacted by preparing it.", "",
        "## Exact technical snapshot", "",
        f"Source revision: [`{sha}`]({repo}/tree/{sha}).",
        "Use the source revision, not a moving branch or latest Release, when recording findings.",
        "Rebuild the PDF from this pinned source using the commands below. No existing",
        "Release or PDF identity is inferred from the commit SHA by this packet.",
        "[The manifest](../research/review-packet.json) pins the technical files by SHA256.",
        "`make check` rejects changed, missing, or newly discovered technical source files",
        "and missing/duplicate claim coverage. It does not authenticate Git history,",
        "verify a reviewer identity, check cited literature, or validate a mathematical proof.", "",
        "The review request includes every current registered claim, but independent review",
        "may be scoped to one unit. Record exclusions explicitly; a partial review is not",
        "approval of the whole manuscript. Read the foundations before dependent claims.", "",
        "## Evidence boundaries and decisions", "",
        "- Expository-proved means the repository supplies an expository argument, not",
        "  independent review, a novelty claim, or a proof-assistant certificate.",
        "- Only **L02** and **P03** have separate Lean evidence. Their kernel-checked",
        "  statements and manuscript correspondence must be assessed separately.",
        "  P04, L03/P05, L04, T01, and Q01 are not thereby formalized; neither is",
        "  the surrounding formalization prose or the full SAT encoding infrastructure.",
        "- Q01 is open: SAT not in P/poly. No P versus NP separation is established.",
        "- The all-order grid bound concerns selector-input layered diagrams; those same",
        "  predicates have linear-size general circuits. No transfer to ordinary SAT",
        "  encodings, general circuits, or Gap-MCSP is supplied.",
        "- W04/#6 needs a concrete reduction with direction, promises, overhead, and all",
        "  parameter quantifiers. Its activation condition is still unmet.",
        "- Novelty/bibliography review, contribution choice, licensing, authorship and",
        "  venue/submission decisions remain separate author-controlled gates in",
        "  [PUBLICATION.md](../PUBLICATION.md). No license is selected here.", "",
        "## Reading and review units", "",
    ]
    for index, unit in enumerate(packet["review_units"], 1):
        lines.extend([f"### {index}. {unit['title']} (`{unit['id']}`)", ""])
        for claim_id in unit["claim_ids"]:
            claim = claims[claim_id]
            dependencies = ", ".join(claim["depends_on"]) or "none"
            formal = f"; separate Lean evidence for {claim_id}" if claim.get("formal_evidence") else ""
            lines.append(f"- **{claim_id}** — `{claim['status']}`{formal}; dependencies: {dependencies}.")
        lines.extend(["", "Read:"])
        lines.extend(f"- [`{name}`](../{name})" for name in unit["sources"])
        lines.extend(["", "Questions:"])
        lines.extend(f"{number}. {question}" for number, question in enumerate(unit["questions"], 1))
        lines.append("")
    lines.extend([
        "## Reproduce and return findings", "",
        "From a clean checkout of the pinned source revision:", "",
        "```sh", f"git checkout --detach {sha}",
        "python3 scripts/setup_lean.py",
        'make verify LAKE="$PWD/build/lean/lean-4.35.0-linux/bin/lake"', "```", "",
        "The setup downloads the pinned approximately 595 MB Lean archive; the extracted",
        "toolchain needs approximately 3 GB. See [toolchain requirements](toolchain.md)",
        "and [formal trust/correspondence](../formal/README.md). The packet checker itself",
        "was added after this technical baseline: run `make check` on the packet branch",
        "to verify the fingerprints. Record both revisions if reviewing that branch.", "",
        "Use the [review checklist](review-checklist.md). A return record should include:", "",
        "- Reviewer identity, date, independence from the proof/drafting, and conflicts.",
        "- Exact source revision, claim IDs and proof directions reviewed; exclusions.",
        "- Commands actually run and logs, separated from checks not run or blocked.",
        "- Each finding's source location, hypothesis/counterexample, severity, and affected claims.",
        "- For each correction, the correcting commit and whether it was re-reviewed.",
        "- A scoped conclusion: sound under stated hypotheses, corrections required, or unresolved.", "",
        "Leave these fields unfilled until an actual review occurs. Agent audits, green",
        "CI, the Lean L02/P03 proofs, and a merged PR do not supply independent human review.",
        "A blocking foundation finding suspends the affected dependent assertions until",
        "resolved; retain unresolved findings rather than checking acceptance boxes.", "",
        "## Maintaining this request", "",
        "After changing any pinned source, reassess affected claims and review questions",
        "before replacing hashes and the full source revision in the manifest. Pin an",
        "existing commit containing those technical inputs, not a proposed future SHA.",
        "Before repinning, compare each source fingerprint with the bytes at that commit",
        "using Git, and retain the verification record. This local checker still checks",
        "working-tree consistency, not Git-history authenticity or the presence of a Release.",
        "Generate this document with `python3 scripts/check_review_packet.py --write`,",
        "then run `make check`. Do not carry a review conclusion over to changed inputs",
        "without checking its scope. Fingerprint regeneration is not re-review.", "",
    ])
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true", help="regenerate the review document, not hashes")
    args = parser.parse_args(argv)
    try:
        packet = json.loads((ROOT / MANIFEST).read_text(encoding="utf-8"))
        register = json.loads((ROOT / "research/claims.json").read_text(encoding="utf-8"))
        validate(ROOT, packet, register)
        expected = render(packet, register)
        if args.write:
            (ROOT / DOCUMENT).write_text(expected, encoding="utf-8")
        else:
            require((ROOT / DOCUMENT).read_text(encoding="utf-8") == expected,
                    "Review document is stale; run scripts/check_review_packet.py --write")
    except (KeyError, TypeError, ValueError, OSError) as error:
        print(f"Review packet check failed: {error}", file=sys.stderr)
        return 1
    print(f"Review request verified: {len(register['claims'])} claims, "
          f"{len(packet['source_sha256'])} source fingerprints.")
    print("This checks handoff consistency, not proof correctness or independent human review.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
